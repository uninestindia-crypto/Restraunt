-- The Taste Restaurant OS - safe public launch schema
-- Scope: one restaurant, default store_id = the-taste
-- Safe to run on an existing project. This file does not drop production data.

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

CREATE TABLE IF NOT EXISTS menu_categories (
  id BIGINT PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  name VARCHAR(100) NOT NULL,
  icon VARCHAR(50) DEFAULT '',
  sort_order INT DEFAULT 0,
  is_active BOOLEAN DEFAULT TRUE,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS menu_items (
  id BIGINT PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  category_id BIGINT REFERENCES menu_categories(id) ON DELETE SET NULL,
  name VARCHAR(100) NOT NULL,
  price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  is_available BOOLEAN DEFAULT TRUE,
  is_veg BOOLEAN DEFAULT TRUE,
  sort_order INT DEFAULT 0,
  image_url VARCHAR(500) DEFAULT '',
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  client_order_id UUID,
  idempotency_key TEXT,
  order_number VARCHAR(50) UNIQUE NOT NULL,
  display_token VARCHAR(20),
  type VARCHAR(20) DEFAULT 'takeaway',
  status VARCHAR(20) DEFAULT 'pending',
  channel VARCHAR(20) DEFAULT 'pos',
  source VARCHAR(20) DEFAULT 'pos',
  items JSONB NOT NULL DEFAULT '[]'::jsonb,
  subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  tax NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  tax_percent NUMERIC(5, 2) DEFAULT 0.00,
  delivery_fee NUMERIC(10, 2) DEFAULT 0.00,
  total NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  payment_method VARCHAR(20),
  payment_status VARCHAR(20) DEFAULT 'unpaid',
  payment_reference TEXT DEFAULT '',
  payment_verified_at TIMESTAMPTZ,
  payment_verified_by TEXT DEFAULT '',
  payment_collected_at TIMESTAMPTZ,
  customer_name VARCHAR(100) DEFAULT '',
  customer_phone VARCHAR(20) DEFAULT '',
  delivery_address TEXT DEFAULT '',
  delivery_landmark TEXT DEFAULT '',
  delivery_notes TEXT DEFAULT '',
  delivery_status VARCHAR(30) DEFAULT 'none',
  delivery_staff_id BIGINT,
  delivery_staff_name VARCHAR(100) DEFAULT '',
  delivery_assigned_at TIMESTAMPTZ,
  delivery_out_at TIMESTAMPTZ,
  delivered_at TIMESTAMPTZ,
  staff_id BIGINT,
  staff_name VARCHAR(100) DEFAULT '',
  table_id BIGINT,
  notes TEXT DEFAULT '',
  requires_server_validation BOOLEAN DEFAULT FALSE,
  validation_status VARCHAR(30) DEFAULT 'trusted_staff',
  sync_attempts INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  completed_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS tables (
  id BIGINT PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  number INT NOT NULL,
  capacity INT DEFAULT 2,
  floor_section VARCHAR(50) DEFAULT 'Main',
  status VARCHAR(20) DEFAULT 'available',
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS inventory (
  id BIGINT PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  name VARCHAR(100) NOT NULL,
  quantity NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  min_threshold NUMERIC(10, 2) DEFAULT 0.00,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS suppliers (
  id BIGINT PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  name VARCHAR(100) NOT NULL,
  contact VARCHAR(150) DEFAULT '',
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS staff (
  id BIGINT PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  auth_user_id UUID,
  name VARCHAR(100) NOT NULL,
  role VARCHAR(30) NOT NULL CHECK (role IN ('owner', 'manager', 'cashier', 'kitchen', 'waiter', 'delivery')),
  pin_hash VARCHAR(64) NOT NULL,
  allow_express BOOLEAN DEFAULT FALSE,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS staff_memberships (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  staff_id BIGINT REFERENCES staff(id) ON DELETE CASCADE,
  auth_user_id UUID NOT NULL,
  role VARCHAR(30) NOT NULL CHECK (role IN ('owner', 'manager', 'cashier', 'kitchen', 'waiter', 'delivery')),
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE (store_id, auth_user_id)
);

CREATE TABLE IF NOT EXISTS shifts (
  id BIGINT PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  staff_id BIGINT REFERENCES staff(id) ON DELETE CASCADE,
  clock_in VARCHAR(50),
  clock_out VARCHAR(50),
  date VARCHAR(30),
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS activity_log (
  id BIGINT PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  timestamp TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  action VARCHAR(150) NOT NULL,
  staff_name VARCHAR(100) DEFAULT 'System',
  details TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  actor_staff_id BIGINT,
  actor_auth_user_id UUID,
  action TEXT NOT NULL,
  target_table TEXT,
  target_id TEXT,
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS customers (
  id BIGINT PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  auth_user_id UUID,
  name VARCHAR(100) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  birthday VARCHAR(30),
  total_spent NUMERIC(10, 2) DEFAULT 0.00,
  visit_count INT DEFAULT 0,
  loyalty_points INT DEFAULT 0,
  tier VARCHAR(20) DEFAULT 'bronze',
  last_visit TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE (store_id, phone)
);

CREATE TABLE IF NOT EXISTS public_order_rate_limits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id TEXT NOT NULL DEFAULT 'the-taste',
  ip_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE orders ADD COLUMN IF NOT EXISTS client_order_id UUID;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS idempotency_key TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS display_token VARCHAR(20);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS requires_server_validation BOOLEAN DEFAULT FALSE;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS validation_status VARCHAR(30) DEFAULT 'trusted_staff';
