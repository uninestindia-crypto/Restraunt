ALTER TABLE staff ADD COLUMN IF NOT EXISTS allow_express BOOLEAN DEFAULT FALSE;
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS image_url VARCHAR(500) DEFAULT '';
