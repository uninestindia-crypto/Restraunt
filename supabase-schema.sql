UPDATE orders SET client_order_id = gen_random_uuid() WHERE client_order_id IS NULL;
UPDATE orders SET idempotency_key = client_order_id::text WHERE idempotency_key IS NULL;
UPDATE orders SET display_token = split_part(order_number, '-', array_length(string_to_array(order_number, '-'), 1)) WHERE display_token IS NULL;

ALTER TABLE orders ALTER COLUMN client_order_id SET NOT NULL;
ALTER TABLE orders ALTER COLUMN idempotency_key SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_client_order_id ON orders(store_id, client_order_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_idempotency_key ON orders(store_id, idempotency_key);
CREATE INDEX IF NOT EXISTS idx_menu_items_category_available ON menu_items(store_id, category_id, is_available);
CREATE INDEX IF NOT EXISTS idx_orders_store_created ON orders(store_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_delivery ON orders(store_id, type, delivery_status);
CREATE INDEX IF NOT EXISTS idx_staff_memberships_auth ON staff_memberships(store_id, auth_user_id) WHERE is_active = TRUE;
CREATE INDEX IF NOT EXISTS idx_rate_limits_window ON public_order_rate_limits(store_id, ip_hash, created_at DESC);

